function lessonsFor(info) {
  if (info && ELEM_LESSONS[info.std]) {
    return ELEM_LESSONS[info.std].map((s, i) => {
      const [title, std, sensor] = s.split('|');
      return { no: i + 1, title, std: std ? `${info.std}-${std}` : '', sensor: sensor || '' };
    });
  }
  return DEFAULT_LESSONS.map((title, i) => ({ no: i + 1, title, std: '', sensor: '' }));
}

function elemSemesters(prefix, from, to) {
  const units = ELEM_UNITS.filter(u => u.std.startsWith(prefix) && u.no >= from && u.no <= to);
  return [{ group: '과학', units }];
}

