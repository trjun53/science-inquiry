function recommendSensors(unitName) {
  const set = [];
  for (const [re, keys] of SENSOR_RULES) {
    if (re.test(unitName || '')) keys.forEach(k => { if (!set.includes(k)) set.push(k); });
  }
  return set.length ? set.slice(0, 4) : ['temp', 'light'];
}
